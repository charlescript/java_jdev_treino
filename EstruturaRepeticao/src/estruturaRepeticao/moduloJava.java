package estruturaRepeticao;

public class moduloJava {
	
	public static void main(String[] args) {
		
		/* Módulo: Resto da divisão % */
		
		double carro = 9;
		double pessoa = 2;
		
		
		double resto = carro % pessoa;
		
		System.out.println("Sobraram exatamente: " + resto + " carros ");
		
	}

}
