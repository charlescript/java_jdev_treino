package javacore.tiposVariaveis;

public class TipoStringDados {
	
	public static void main(String[] args) {
		
		/*String no Java sempre será um texto de tamanho N(caracter)*/
		String texto = "Informativo sobre questões envolvendo a geopolitica global no cenário de 2026";
		String cpf = "123.456.789-10";
		String telefone = "(11) 99183-1548";
		String endereco = "Rua Almirante Danton";
		
		System.out.println(texto);
		System.out.println("CPF:" + cpf);
		System.out.println("Telefone: "+ telefone);
		System.out.println("Endereco: " + endereco);
	}
}
